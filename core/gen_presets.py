#!/usr/bin/env python3
"""Writes core/presets.generated.h from osc440bridge/presets.json: osc440's presets (each as the parameters that
differ from a fresh voice) for builds without the page, the Pi kernel and the host renderer.
Run from the repository root:  python3 core/gen_presets.py"""
import json, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(os.path.join(root, 'osc440bridge', 'presets.json')))
out = ['// Generated by core/gen_presets.py from osc440bridge/presets.json; do not edit.',
       '// osc440 presets as (parameter id, value) pairs that differ from a fresh voice.',
       '#pragma once', '', 'struct PyokoPreset { const char *group; const char *name; int count; const float *pairs; };', '']
def lit(x):
    t = f'{float(x):.9g}'
    return (t if any(c in t for c in '.en') else t + '.') + 'f'

for i, p in enumerate(data['presets']):
    vals = ', '.join(f'{lit(a)}, {lit(b)}' for a, b in p['p']) or '0.f, 0.f'
    out.append(f'static const float kPresetPairs{i}[] = {{{vals}}};')
out.append('')
out.append('static const PyokoPreset kPresets[] = {')
for i, p in enumerate(data['presets']):
    out.append(f'    {{"{p["group"]}", "{p["name"]}", {len(p["p"])}, kPresetPairs{i}}},')
out.append('};')
out.append('static const int kNumPresets = sizeof(kPresets) / sizeof(kPresets[0]);')
open(os.path.join(root, 'core', 'presets.generated.h'), 'w').write('\n'.join(out) + '\n')
